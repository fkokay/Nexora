/// <summary>
/// Sub-project 4: a Kayıt kartı built by Studio's own model (frontend/development-studio …/panel/recordModel.ts, through the
/// designer's wire step) passes the real server validator against a matching active catalog. The definitions under
/// Fixtures/RecordCard are generated by the Studio vitest <c>recordServerFixture.test.ts</c>, which reads
/// <c>catalog-view.json</c>: the catalog view this test checks the server still returns for <c>catalog.json</c>.
/// Regenerate: <c>UPDATE_RECORD_CARD_FIXTURE=1</c> here (view), then <c>UPDATE_RECORD_CARD_FIXTURE=1 npx vitest run recordServerFixture</c> in Studio.
/// </summary>
public sealed class TenantCustomPageRecordStudioFixtureTests
{
    private static readonly Guid TenantA = Guid.Parse("11111111-1111-1111-1111-111111111111");
    private static readonly Guid Admin = CustomPageQueryEndpointsIntegrationTests.Admin;
    private static readonly Guid Ayse = CustomPageCatalogReferenceEndpointsIntegrationTests.Ayse;
    private const string FixtureDirectory = "RecordCardFixtures";
    private const string UpdateVariable = "UPDATE_RECORD_CARD_FIXTURE";

    private static string Fixture(string name) => File.ReadAllText(Path.Combine(AppContext.BaseDirectory, FixtureDirectory, name));
    private static JsonElement FixtureElement(string name) => JsonDocument.Parse(Fixture(name)).RootElement.Clone();

    [Fact]
    public async Task Catalog_view_matches_the_fixture_studio_builds_from()
    {
        await using var app = await StartApplicationAsync();
        using var client = app.GetTestClient();
        await ActivateCatalogAsync(client);

        var view = JsonNode.Parse(await client.GetStringAsync("/api/custom-pages/catalog"))!.AsObject();
        var actual = new JsonObject { ["version"] = view["version"]!.DeepClone(), ["dataSources"] = view["dataSources"]!.DeepClone(), ["actions"] = view["actions"]!.DeepClone() };
        Assert.Empty(view["invalidItems"]!.AsArray());
        if (Environment.GetEnvironmentVariable(UpdateVariable) == "1") { WriteSourceFixture("catalog-view.json", actual); return; }
        Assert.True(JsonNode.DeepEquals(JsonNode.Parse(Fixture("catalog-view.json")), actual), actual.ToJsonString());
    }

    [Theory]
    [InlineData("definition-typed-key.json")]
    [InlineData("definition-system-key.json")]
    public async Task Studio_built_record_card_saves_as_page_writer_and_admin_and_publishes(string fixture)
    {
        var definition = FixtureElement(fixture);
        AssertCoverage(fixture, definition);
        await using var app = await StartApplicationAsync();
        using var client = app.GetTestClient();
        await ActivateCatalogAsync(client);

        // Karar 1 (alt proje 3): a catalog reference carries only a code, so a non-admin page writer may save it.
        CustomPageQueryEndpointsIntegrationTests.SetIdentity(client, Ayse, "TenantUser");
        var created = await client.PostAsJsonAsync("/api/custom-pages/drafts", new { code = "cari-karti", name = "Cari kartı", definition });
        Assert.True(created.StatusCode == HttpStatusCode.Created, await created.Content.ReadAsStringAsync());
        var detail = await created.Content.ReadFromJsonAsync<JsonElement>();
        var id = detail.GetProperty("id").GetGuid();
        AssertStored(definition, detail.GetProperty("definitionJson").GetString()!);
        var updated = await client.PutAsJsonAsync($"/api/custom-pages/{id}", new { expectedRevision = 1, name = "Cari kartı", definition });
        Assert.True(updated.StatusCode == HttpStatusCode.OK, await updated.Content.ReadAsStringAsync());

        // The same definition saved by a TenantAdmin, then published.
        CustomPageQueryEndpointsIntegrationTests.SetIdentity(client, Admin, "TenantAdmin");
        var saved = await client.PutAsJsonAsync($"/api/custom-pages/{id}", new { expectedRevision = 2, name = "Cari kartı", definition });
        Assert.True(saved.StatusCode == HttpStatusCode.OK, await saved.Content.ReadAsStringAsync());
        var adminDraft = await client.PostAsJsonAsync("/api/custom-pages/drafts", new { code = "cari-karti-2", name = "Cari kartı 2", definition });
        Assert.True(adminDraft.StatusCode == HttpStatusCode.Created, await adminDraft.Content.ReadAsStringAsync());
        Assert.Equal(HttpStatusCode.OK, (await client.PutAsJsonAsync("/api/custom-pages/cari-karti/access", new { mode = "AllUsers", expectedRevision = 0 })).StatusCode);
        var published = await client.PostAsJsonAsync($"/api/custom-pages/{id}/publish", new { expectedRevision = 3 });
        Assert.True(published.StatusCode == HttpStatusCode.OK, await published.Content.ReadAsStringAsync());

        var runtime = await client.GetFromJsonAsync<JsonElement>("/api/custom-pages/cari-karti/published");
        using var runtimeDefinition = JsonDocument.Parse(runtime.GetProperty("definitionJson").GetString()!);
        Assert.Equal("record", runtimeDefinition.RootElement.GetProperty("template").GetProperty("name").GetString());
        Assert.Equal(definition.GetProperty("components").GetArrayLength(), runtimeDefinition.RootElement.GetProperty("components").GetArrayLength());
    }

    /// <summary>The server stores what Studio sent, unchanged.</summary>
    private static void AssertStored(JsonElement sent, string storedJson)
    {
        using var stored = JsonDocument.Parse(storedJson);
        Assert.True(JsonElement.DeepEquals(sent, stored.RootElement), storedJson);
    }

    /// <summary>A regenerated fixture must keep exercising every rule this test is meant to cover.</summary>
    private static void AssertCoverage(string fixture, JsonElement definition)
    {
        Assert.Equal("record", definition.GetProperty("template").GetProperty("name").GetString());
        var queries = definition.GetProperty("queries").EnumerateArray().ToList();
        var components = definition.GetProperty("components").EnumerateArray().ToList();
        JsonElement Props(JsonElement component) => component.GetProperty("props");
        bool Has(JsonElement component, string prop) => Props(component).TryGetProperty(prop, out _);
        string? Text(JsonElement component, string prop) => Props(component).TryGetProperty(prop, out var value) && value.ValueKind == JsonValueKind.String ? value.GetString() : null;
        IEnumerable<JsonElement> OfType(string type) => components.Where(x => x.GetProperty("type").GetString() == type);

        var record = Assert.Single(queries, x => x.GetProperty("id").GetString() == "kayit");
        Assert.Equal("cariKart", record.GetProperty("dataSource").GetString());
        Assert.Equal("{{sayfa.parametre.kod}}", record.GetProperty("parameters")[0].GetProperty("binding").GetString());
        Assert.Contains(queries, x => x.TryGetProperty("dataSource", out var ds) && ds.GetString() == "cariHareket");
        foreach (var kind in new[] { "insert", "update", "delete" })
            Assert.Contains(queries, x => x.GetProperty("kind").GetString() == kind && x.TryGetProperty("action", out _));

        var fields = OfType("input").ToList();
        var key = Assert.Single(fields, x => Text(x, "defaultValue") == "{{kayit.rows[0].kod}}");
        if (fixture.Contains("typed", StringComparison.Ordinal))
        {
            Assert.Equal("kayit.rows[0].kod != null", Text(key, "disabledWhen"));
            Assert.False(string.IsNullOrEmpty(Text(key, "disabledReason")));
        }
        else
        {
            Assert.True(Props(key).GetProperty("readOnly").GetBoolean());
            Assert.Equal("(otomatik)", Text(key, "placeholder"));
        }
        Assert.Contains(fields, x => Has(x, "required"));
        Assert.Contains(fields, x => Has(x, "maxLength"));
        Assert.Contains(fields, x => Has(x, "multiline"));
        Assert.Contains(fields, x => Has(x, "readOnly") && Text(x, "defaultValue") != "{{kayit.rows[0].kod}}");

        var summary = Assert.Single(OfType("recordHeader"));
        Assert.Contains(" · ", Text(summary, "subtitle"));
        Assert.True(Props(summary).GetProperty("fields").GetArrayLength() > 0);
        Assert.True(Props(summary).GetProperty("fieldFormats").GetArrayLength() > 0);

        var lines = Assert.Single(OfType("dataTable"));
        Assert.Equal("lines", Text(lines, "slot"));
        Assert.Equal(25, Props(lines).GetProperty("pageSize").GetInt32());
        Assert.True(Props(lines).GetProperty("columnLabels").GetArrayLength() > 0);

        var buttons = OfType("button").ToList();
        Assert.Contains(buttons, x => Text(x, "actionType") == "sequence" && Has(x, "sequenceWhen"));
        Assert.Contains(buttons, x => Text(x, "actionType") == "query" && Has(x, "refreshQueries") && Props(x).GetProperty("confirmEnabled").GetBoolean());
    }

    private static async Task ActivateCatalogAsync(HttpClient client)
    {
        CustomPageQueryEndpointsIntegrationTests.SetIdentity(client, Admin, "TenantAdmin");
        var create = await client.PostAsJsonAsync("/api/custom-pages/catalog/releases",
            new { version = "1.0.0", bundle = JsonDocument.Parse(Fixture("catalog.json")).RootElement, sourcePath = "catalog.json" });
        Assert.True(create.StatusCode == HttpStatusCode.Created, await create.Content.ReadAsStringAsync());
        var releaseId = (await create.Content.ReadFromJsonAsync<JsonElement>()).GetProperty("id").GetGuid();
        var activate = await client.PostAsJsonAsync($"/api/custom-pages/catalog/releases/{releaseId}/activate", new { expectedActiveReleaseId = (Guid?)null });
        Assert.True(activate.StatusCode == HttpStatusCode.OK, await activate.Content.ReadAsStringAsync());
    }

    private static void WriteSourceFixture(string name, JsonNode node, [CallerFilePath] string source = "")
    {
        var path = Path.Combine(Path.GetDirectoryName(source)!, "Fixtures", "RecordCard", name);
        File.WriteAllText(path, node.ToJsonString(new JsonSerializerOptions { WriteIndented = true, Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping }) + "\n");
    }

    private static async Task<WebApplication> StartApplicationAsync()
    {
        var builder = WebApplication.CreateBuilder();
        builder.WebHost.UseTestServer();
        var suffix = Guid.NewGuid().ToString("N");
        builder.Services.AddDbContext<TenantDbContext>(options => options
            .UseInMemoryDatabase($"record-fixture-tenant-{suffix}")
            .ConfigureWarnings(warnings => warnings.Ignore(InMemoryEventId.TransactionIgnoredWarning)));
        builder.Services.AddDbContext<PlatformDbContext>(options => options
            .UseInMemoryDatabase($"record-fixture-platform-{suffix}")
            .ConfigureWarnings(warnings => warnings.Ignore(InMemoryEventId.TransactionIgnoredWarning)));
        builder.Services.AddAuthentication("report-test").AddScheme<AuthenticationSchemeOptions, ReportTestAuthenticationHandler>("report-test", _ => { });
        builder.Services.AddSingleton<IPlatformPermissionAuthorizer, CustomPageQueryRulesIntegrationTests.AllowAllPermissionAuthorizer>();
        builder.Services.AddAuthorization();

        var app = builder.Build();
        app.UseAuthentication();
        app.UseAuthorization();
        app.MapTenantCustomPageEndpoints();
        app.MapTenantCatalogEndpoints();
        app.MapCustomPageAccessEndpoints();
        await app.StartAsync();
        await using var scope = app.Services.CreateAsyncScope();
        var tenantDb = scope.ServiceProvider.GetRequiredService<TenantDbContext>();
        await tenantDb.Database.EnsureCreatedAsync();
        tenantDb.Tenants.Add(new Tenant { Id = TenantA, Name = "Tenant A", Slug = "tenant-a" });
        await tenantDb.SaveChangesAsync();
        await CustomPageAccessEndpointsIntegrationTests.SeedPlatformAsync(scope.ServiceProvider.GetRequiredService<PlatformDbContext>());
        return app;
    }
}
